MANIFEST_NAME = 'corrected_preparation_manifest.json'
REPORT_FILES = frozenset(('report.json', 'readable_report.html', 'telemetry.csv'))
OBSERVATION_FILES = frozenset(REQUIRED_PIPELINE_FILES) - EXPORT_FILES - VIDEO_FILES
OPTIONAL_OBSERVATION_FILES = frozenset(OPTIONAL_PIPELINE_FILES) - {'landing_zones.json'}


def _require(condition, message):
    if not condition:
        raise ValueError('Corrected preparation: ' + message)


def _small_value(storage, value):
    """Detach only bounded metadata, including any foreign lazy small arrays."""
    pieces, length = [], 0
    with closing(storage.json_chunks(value)) as chunks:
        for chunk in chunks:
            length += len(chunk.encode('utf-8'))
            _require(length <= 64*1024, 'original result metadata exceeds its bounded size')
            pieces.append(chunk)
    return json.loads(''.join(pieces))


def _json_digest(storage, value):
    digest = hashlib.sha256()
    with closing(storage.json_chunks(value)) as chunks:
        for chunk in chunks:
            digest.update(chunk.encode('utf-8'))
    return digest.hexdigest()


def _write_report(path, chunks):
    """Bind the generated bytes before any subsequent producer can alter them."""
    digest, size = hashlib.sha256(), 0
    with closing(chunks), _destination(path) as stream:
        for chunk in chunks:
            encoded = chunk.encode('utf-8')
            digest.update(encoded)
            size += len(encoded)
            stream.write(chunk)
    expected = {'bytes': size, 'sha256': digest.hexdigest()}
    _require(_file_record(path) == expected, 'serialized report bytes changed during writing: '+path.name)
    return expected


def _same_rows(first, second):
    """Compare owned JSON sequences without materializing the full match."""
    sentinel = object()
    # DiskSeries readers are closeable; ordinary empty/small lists are not.
    from src.scoring.corrected_rendering import _reader
    with _reader(first) as left, _reader(second) as right:
        for actual, expected in zip_longest(left, right, fillvalue=sentinel):
            _require(actual is not sentinel and expected is not sentinel
                     and _digest(actual) == _digest(expected),
                     'normalized landing records differ from strict fresh evidence')


def _frozen_manifest(path, expected_sha):
    payload = _read_small(path)
    _require(hashlib.sha256(payload).hexdigest() == expected_sha,
             'producer manifest bytes changed after its native seal: '+path.name)
    document = _json(payload)
    _require(type(document) is dict and type(document.get('artifacts')) is dict,
             'producer manifest artifact records are missing')
    return document, {'bytes': len(payload), 'sha256': expected_sha}


def _render_guard(rebuilt, exports, rendered, directory, binding):
    _require(isinstance(rendered, CorrectedRenderResult), 'native sealed render result is required')
    stage = _scratch(rendered.directory, rebuilt.snapshot.files_directory.parent.parent.resolve())
    names = VIDEO_FILES | {RENDER_MANIFEST}
    _require(stage.parent == directory and set(rendered.files) == names
             and {path.name for path in stage.iterdir()} == names
             and all(rendered.files[name] == stage/name for name in names),
             'render inventory or artifact path differs')
    for name in names:
        path = _safe_path(stage/name)
        _require(path.is_file(), 'render artifact is missing')
    seal = stage/RENDER_MANIFEST
    document, _ = _frozen_manifest(seal, rendered.manifest_sha256)
    expected = {**binding, 'schema_version': '1.0',
        'status': 'PRIVATE_PENDING_REPORT_AND_PUBLICATION',
        'export_manifest_sha256': exports.manifest_sha256,
        'frames': rebuilt.snapshot.frames, 'fps': rebuilt.sources.fps,
        'human_review_dependent': True, 'independent_accuracy_validated': False, 'published': False}
    _require(type(document) is dict and all(document.get(key) == value for key, value in expected.items()),
             'render manifest source, revision or export binding differs')
    artifacts = document.get('artifacts')
    _require(type(artifacts) is dict and set(artifacts) == VIDEO_FILES,
             'render artifact inventory differs')
    for name, record in artifacts.items():
        _require(_file_record(stage/name) == record, 'render artifact bytes/hash changed: '+name)
    return stage, document


def _base_inputs(rebuilt, job):
    snapshot = rebuilt.snapshot
    _require(isinstance(job, dict) and job.get('id') == snapshot.analysis_id,
             'job analysis binding differs')
    extension = job.get('extension')
    _require(type(extension) is str and re.fullmatch(r'\.[A-Za-z0-9]{1,10}', extension),
             'job original extension is invalid')
    originals = [name for name in snapshot._files if name.startswith('original.')]
    _require(originals == ['original'+extension], 'sole sealed original artifact or job extension differs')
    paths = {}
    for name in OBSERVATION_FILES | set(originals):
        path = snapshot.resolve_file(name)
        _require(path is not None, 'required sealed original observation artifact is missing: '+name)
        paths[name] = path
    for name in OPTIONAL_OBSERVATION_FILES:
        path = snapshot.resolve_file(name)
        if path is not None:
            paths[name] = path
    analysis = snapshot.files_directory.parent.parent
    with ResultDocument(analysis, snapshot.analysis_id, generation=snapshot.generation) as document:
        _require(document.snapshot == snapshot, 'original result generation binding differs')
        summary = _small_value(document.storage, document.value['summary'])
        captured = document.value.get('provenance')
        provenance = _small_value(document.storage, captured) if captured is not None else None
        database_sha = artifact_sha256(snapshot.database)
    _require(type(summary) is dict and summary.get('id') == snapshot.analysis_id,
             'original result summary belongs to another analysis')
    unknown = provenance is None
    if unknown:
        provenance = {'bundleVersion': None, 'bundleStatus': 'ORIGINAL_INFERENCE_PROVENANCE_UNAVAILABLE',
            'productionQualified': False, 'configSha256': None, 'bundleSha256': None,
            'checkpointHashes': {}, 'datasetHashes': {}, 'codeCommit': None,
            'unavailableReason': 'The sealed original result contains no captured inference provenance.'}
    _require(type(provenance) is dict, 'retained inference provenance must be an object')
    config_sha = provenance.get('configSha256')
    _require(config_sha is None or config_sha == snapshot.file_sha256('inference_config.yaml'),
             'retained inference provenance config hash differs from sealed original observations')
    provenance['productionQualified'] = False
    # Caller filenames and timestamps are neither original evidence nor an
    # authorization decision. Preserve the original summary's display metadata.
    filename = summary.get('sourceVideoPath')
    if type(filename) is not str or not filename:
        filename = snapshot.analysis_id+extension
    label = summary.get('label')
    if type(label) is not str or not label:
        label = filename
    analyzed_at = summary.get('analyzedAt')
    _require(analyzed_at is None or type(analyzed_at) is str, 'original analysis timestamp is invalid')
    normalized_job = {'id': snapshot.analysis_id, 'filename': filename, 'extension': extension,
                      'started_at': analyzed_at, 'completed_at': analyzed_at}
    return paths, normalized_job, label, provenance, unknown, database_sha


def _strict_normalized(stage, result, rebuilt, storage):
    binding = {'analysisId': rebuilt.owner.analysis_id, 'analysisRevision': rebuilt.owner.revision,
               'sourceSha256': rebuilt.owner.source_fingerprint}
    points = result.get('pointAnalysis')
    _require(type(points) is dict and all(points.get(key) == value for key, value in binding.items())
             and result.get('analysisRevision') == binding['analysisRevision'],
             'normalized point analysis lost its strict source/revision binding')
    raw = storage.read_json(stage/'landing_zones.json', indexed_root_objects=('calibrations',))
    strict = validate_landing_zones(raw, binding['analysisId'], result['events'],
        frame_calibrations=result['cameraTracking']['frames'], expected_revision=binding['analysisRevision'])
    _same_rows(result.get('landingZones', ()), strict)


@dataclass(frozen=True)
class PreparedCorrection:
    directory: Path
    storage: object
    result: dict
    files: object
    manifest_sha256: str
    base_generation: str
    analysis_revision: int


@contextmanager
def prepare_corrected_result(rebuilt, shot_analysis, forecast, exports, rendered, scratch, *, job):
    """Prepare one complete result, retaining diagnostics without a failed seal.

    Consumers must finish inside this context. Both the exposed lazy result
    and stored root are checked against the sealed report before successful
    exit. A later publisher must still perform authenticated admission and an
    expected-base compare-and-swap; this helper never changes current.store.
    """
    directory, binding, export_stage, event_generation = _guard_exports(
        rebuilt, shot_analysis, forecast, exports, scratch)
    render_stage, render_manifest = _render_guard(rebuilt, exports, rendered, directory, binding)
    export_manifest, export_seal_record = _frozen_manifest(
        export_stage/EXPORT_MANIFEST, exports.manifest_sha256)
    _, render_seal_record = _frozen_manifest(render_stage/RENDER_MANIFEST, rendered.manifest_sha256)
    paths, normalized_job, label, provenance, unknown, database_sha = _base_inputs(rebuilt, job)
    stage = Path(tempfile.mkdtemp(prefix='corrected-prepared-', dir=directory))
    seal = stage/MANIFEST_NAME
    command = rebuilt.request

    def guard():
        fresh = _guard_exports(rebuilt, shot_analysis, forecast, exports, scratch)
        _require(fresh[3] == event_generation, 'physical events changed during result preparation')
        _render_guard(rebuilt, exports, rendered, directory, binding)
        for name, path in paths.items():
            _require(rebuilt.snapshot.resolve_file(name) == path,
                     'original observation artifact path changed: '+name)
        _require(artifact_sha256(rebuilt.snapshot.database) == database_sha,
                 'original result provenance database changed')

    try:
        # Exactly one fresh semantic/render source supplies each replacement.
        all_sources = {**paths, **dict(exports.files), **dict(rendered.files)}
        _require(len(all_sources) == len(paths)+len(exports.files)+len(rendered.files),
                 'fresh and retained observation artifact inventories overlap')
        # The immutable producer seals, rather than the current source bytes,
        # define the expected copy. A transient change followed by restoration
        # must not supply different bytes to a newly valid complete bundle.
        expected_sources = {name: dict(rebuilt.snapshot._files[name]) for name in paths}
        expected_sources.update(export_manifest['artifacts'])
        expected_sources.update(render_manifest['artifacts'])
        expected_sources[EXPORT_MANIFEST] = export_seal_record
        expected_sources[RENDER_MANIFEST] = render_seal_record
        _require(set(expected_sources) == set(all_sources), 'trusted copy artifact inventory differs')
        expected_artifacts = {}
        for name, source in sorted(all_sources.items()):
            _safe_path(source)
            record = expected_sources[name]
            _require(_file_record(source) == record, 'source artifact hash differs before copy: '+name)
            _copy(source, stage/name, record['sha256'])
            expected_artifacts[name] = record

        def check_artifacts():
            for name, record in expected_artifacts.items():
                _require(_file_record(stage/name) == record,
                         'prepared copied or serialized artifact bytes changed: '+name)

        check_artifacts()
        # SQLite stays outside the artifact inventory and belongs only to this
        # context. Every normalized series and forecast row uses this one owner.
        with _ephemeral_storage(directory) as storage:
            strict_points = load_point_analysis(stage, binding['analysis_id'],
                frame_count=rebuilt.snapshot.frames, authoritative=rebuilt.authoritative_events_enabled,
                storage=storage)
            landing = storage.read_json(stage/'landing_zones.json', indexed_root_objects=('calibrations',))
            events = storage.read_json(stage/'match_events.json')['events']
            validate_landing_zones(landing, binding['analysis_id'], events,
                frame_calibrations=_CameraRecords(rebuilt.sources), expected_revision=binding['analysis_revision'])
            result = build_result(stage, normalized_job, _storage=storage, _inference_provenance=provenance)
            result['summary']['label'] = label
            _strict_normalized(stage, result, rebuilt, storage)
            _require(_json_digest(storage, result['pointAnalysis']) == _json_digest(storage, strict_points),
                     'normalized point analysis differs from strict fresh evidence')
            result['nativeForecast'] = build_corrected_forecast_presentation(rebuilt, shot_analysis, forecast, storage)
            result['analysisCorrection'] = {'schemaVersion': '1.0', 'status': 'PRIVATE_PENDING_PUBLICATION',
                'analysisId': binding['analysis_id'], 'analysisRevision': binding['analysis_revision'],
                'sourceSha256': binding['source_sha256'], 'baseGeneration': binding['base_generation'],
                'requestSha256': _digest(command), 'exportManifestSha256': exports.manifest_sha256,
                'renderManifestSha256': rendered.manifest_sha256,
                'originalResultDatabaseSha256': database_sha,
                'correctedAt': datetime.now(timezone.utc).isoformat(),
                'review': {'correctionId': command['correction_id'], 'reviewerId': command['reviewer_id'],
                    'reason': command['reason'], 'evidenceRef': command['evidence_ref'],
                    'inputAmendmentCount': len(command['input_amendments']),
                    'initialStateAmended': command['initial_state_amendment'] is not None,
                    'humanReviewDependent': True},
                'authorizationStatus': 'PRIVATE_LOCAL_REVIEW_NOT_AUTHENTICATED',
                'independentAccuracyValidated': False, 'published': False}
            if unknown:
                result['warnings'].append('Original inference provenance is unavailable in the sealed base result.')
            source = result.get('mediaSource')
            credit_name = set()
            if source is not None:
                # New derivative hash and modifications; an old sidecar can
                # never describe this freshly corrected annotated video.
                suffix = ' Fresh corrected overlays, score timeline and uncalibrated forecasts; human review dependent.'
                modifications = source['modifications'][:1000-len(suffix)]+suffix
                credit = {'schemaVersion': 1,
                    'analysisId': binding['analysis_id'], 'inputSha256': source['inputSha256'],
                    'sourceSha256': source['sourceSha256'],
                    'annotatedSha256': artifact_sha256(stage/'annotated_web.mp4'), 'modifications': modifications}
                _object(stage/'annotated_web_credit.json', credit)
                encoded = json.dumps(credit, allow_nan=False, separators=(',', ':'))+'\n'
                expected_artifacts['annotated_web_credit.json'] = {
                    'bytes': len(encoded.encode('utf-8')),
                    'sha256': hashlib.sha256(encoded.encode('utf-8')).hexdigest()}
                # Static HTML, JSON and CSV describe this derivative too. The
                # independently copied media_source.json retains the complete
                # original attribution and modification record unchanged.
                result['mediaSource'] = {**source, 'modifications': modifications}
                credit_name.add('annotated_web_credit.json')
            names = set(all_sources) | REPORT_FILES | credit_name
            # build_result enumerates only files already present. Advertise
            # the final private assets rather than an order-dependent subset.
            result['summary']['artifacts'] = sorted(names | {MANIFEST_NAME})
            storage.set_root(result)
            check_artifacts()
            expected_artifacts['report.json'] = _write_report(stage/'report.json', storage.json_chunks(result))
            for name, chunks in (('readable_report.html', readable_report_chunks(result, stage)),
                                 ('telemetry.csv', telemetry_csv_chunks(result))):
                expected_artifacts[name] = _write_report(stage/name, chunks)
                check_artifacts()
            guard()
            check_artifacts()
            artifacts = {name: expected_artifacts[name] for name in sorted(names)}
            report_sha = artifacts['report.json']['sha256']
            _require(_json_digest(storage, result) == report_sha == _json_digest(storage, storage.root()),
                     'prepared result changed while reports were serialized')
            _object(seal, {**binding, 'schema_version': '1.0', 'status': 'PRIVATE_PENDING_PUBLICATION',
                'request_sha256': _digest(command), 'export_manifest_sha256': exports.manifest_sha256,
                'render_manifest_sha256': rendered.manifest_sha256,
                'original_result_database_sha256': database_sha, 'artifacts': artifacts,
                'human_review_dependent': True, 'independent_accuracy_validated': False, 'published': False})
            seal_sha = artifact_sha256(seal)
            prepared = PreparedCorrection(stage, storage, result,
                MappingProxyType({name: stage/name for name in sorted(names | {MANIFEST_NAME})}),
                seal_sha, binding['base_generation'], binding['analysis_revision'])

            def prepared_guard():
                guard()
                _require({path.name for path in stage.iterdir()} == set(prepared.files),
                         'prepared artifact inventory changed')
                _require(_file_record(seal)['sha256'] == seal_sha, 'prepared manifest changed after sealing')
                for name, record in artifacts.items():
                    _require(_file_record(stage/name) == record, 'prepared artifact bytes changed: '+name)
                _require(_json_digest(storage, result) == report_sha == _json_digest(storage, storage.root()),
                         'prepared result changed after report serialization')

            prepared_guard()
            yield prepared
            prepared_guard()
    except BaseException as error:
        try:
            seal.unlink(missing_ok=True)
        except BaseException as cleanup:
            error.add_note('Preparation seal cleanup also failed: '+str(cleanup))
        raise
